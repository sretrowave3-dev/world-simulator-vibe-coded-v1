# 3. COMPONENTIZED SOLVER INTERFACES & STAGE REGISTRY
# =====================================================================

class ISolverStage(ABC):
    """Base interface for all decoupled pipeline solver stages."""
    
    @property
    @abstractmethod
    def name(self) -> str:
        pass

    @property
    @abstractmethod
    def dependencies(self) -> List[str]:
        """Names of solver stages that MUST execute prior to this stage."""
        pass

    @abstractmethod
    def execute(
        self,
        chunks: List[ChunkData],
        season: SeasonState,
        storm_influences: Dict[int, StormInfluence],
        dt: float
    ) -> None:
        pass


class ThermalSolver(ISolverStage):
    def __init__(self, config: ThermalConfig) -> None:
        self.config = config

    @property
    def name(self) -> str:
        return "ThermalSolver"

    @property
    def dependencies(self) -> List[str]:
        return []

    def execute(
        self,
        chunks: List[ChunkData],
        season: SeasonState,
        storm_influences: Dict[int, StormInfluence],
        dt: float
    ) -> None:
        for chunk in chunks:
            # Solar radiation heat flux based on latitude and insolation
            lat_factor = math.cos(math.radians(chunk.latitude))
            insolation = season.insolation_factor * lat_factor
            
            for i in range(len(chunk.temperature)):
                altitude_cooling = chunk.elevation * self.config.lapse_rate
                target_temp = (25.0 * insolation) - altitude_cooling
                chunk.temperature[i] += (target_temp - chunk.temperature[i]) * 0.1 * dt


class PressureFieldSolver(ISolverStage):
    @property
    def name(self) -> str:
        return "PressureFieldSolver"

    @property
    def dependencies(self) -> List[str]:
        return ["ThermalSolver"]

    def execute(
        self,
        chunks: List[ChunkData],
        season: SeasonState,
        storm_influences: Dict[int, StormInfluence],
        dt: float
    ) -> None:
        sea_level_pressure = 1013.25
        for chunk in chunks:
            influence = storm_influences.get(chunk.chunk_id)
            p_drop = influence.pressure_drop if influence else 0.0
            
            for i in range(len(chunk.pressure)):
                temp = chunk.temperature[i]
                # Barometric pressure variation driven by localized thermal field
                thermal_pressure_delta = (25.0 - temp) * 0.5
                chunk.pressure[i] = sea_level_pressure + thermal_pressure_delta - p_drop


class MoistureSolver(ISolverStage):
    @property
    def name(self) -> str:
        return "MoistureSolver"

    @property
    def dependencies(self) -> List[str]:
        return ["ThermalSolver"]

    def execute(
        self,
        chunks: List[ChunkData],
        season: SeasonState,
        storm_influences: Dict[int, StormInfluence],
        dt: float
    ) -> None:
        for chunk in chunks:
            for i in range(len(chunk.humidity)):
                # Evaporation capacity tied to localized temperature
                sat_humidity = 0.01 * math.exp(0.06 * chunk.temperature[i])
                chunk.humidity[i] = min(1.0, chunk.humidity[i] + sat_humidity * 0.01 * dt)


class StormSystem(ISolverStage):
    """Generates storm influence fields without mutating chunk state directly."""
    
    @property
    def name(self) -> str:
        return "StormSystem"

    @property
    def dependencies(self) -> List[str]:
        return ["ThermalSolver", "PressureFieldSolver"]

    def execute(
        self,
        chunks: List[ChunkData],
        season: SeasonState,
        storm_influences: Dict[int, StormInfluence],
        dt: float
    ) -> None:
        for chunk in chunks:
            avg_temp = sum(chunk.temperature) / len(chunk.temperature)
            avg_press = sum(chunk.pressure) / len(chunk.pressure)
            
            # Low pressure + high temperature triggers storm front formation
            if avg_temp > 20.0 and avg_press < 1005.0:
                storm_influences[chunk.chunk_id] = StormInfluence(
                    chunk_id=chunk.chunk_id,
                    vorticity_boost=12.5,
                    moisture_uplift=0.35,
                    pressure_drop=15.0
                )


class CloudFormationSolver(ISolverStage):
    @property
    def name(self) -> str:
        return "CloudFormationSolver"

    @property
    def dependencies(self) -> List[str]:
        return ["MoistureSolver", "StormSystem"]

    def execute(
        self,
        chunks: List[ChunkData],
        season: SeasonState,
        storm_influences: Dict[int, StormInfluence],
        dt: float
    ) -> None:
        for chunk in chunks:
            influence = storm_influences.get(chunk.chunk_id)
            uplift = influence.moisture_uplift if influence else 0.0
            
            for i in range(len(chunk.cloud_cover)):
                relative_humidity = chunk.humidity[i]
                chunk.cloud_cover[i] = min(1.0, (relative_humidity * 0.8) + uplift)


class ClimateClassifier:
    """Interval-driven solver for expensive climate zone reclassifications."""
    
    def __init__(self, interval_ticks: int = 100) -> None:
        self.interval_ticks = interval_ticks
        self._ticks_elapsed: int = 0

    def tick(self, chunks: List[ChunkData], force: bool = False) -> None:
        self._ticks_elapsed += 1
        if not force and self._ticks_elapsed % self.interval_ticks != 0:
            return

        for chunk in chunks:
            if chunk.dirty_climate or force or (self._ticks_elapsed % self.interval_ticks == 0):
                avg_temp = sum(chunk.temperature) / len(chunk.temperature)
                if avg_temp < -5.0:
                    chunk.climate = ClimateType.TUNDRA
                elif avg_temp < 5.0:
                    chunk.climate = ClimateType.TAIGA
                elif avg_temp > 25.0:
                    chunk.climate = ClimateType.DESERT
                else:
                    chunk.climate = ClimateType.TEMPERATE
                chunk.dirty_climate = False


