import math
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from enum import Enum, auto
from typing import Dict, List, Optional, Protocol, Tuple, Type


# =====================================================================
# 1. DOMAIN DATA MODELS & ISOLATED STATES
# =====================================================================

class ClimateType(Enum):
    TUNDRA = auto()
    TAIGA = auto()
    TEMPERATE = auto()
    DESERT = auto()
    TROPICAL = auto()


@dataclass
class SeasonState:
    day_of_year: float = 0.0
    solar_declination: float = 0.0  # Radians
    insolation_factor: float = 1.0


@dataclass
class ChunkData:
    """Struct-of-Arrays (SoA) friendly layout for localized atmospheric memory."""
    chunk_id: int
    latitude: float
    longitude: float
    elevation: float
    
    # Grid cell arrays (e.g., 16x16 per chunk)
    temperature: List[float] = field(default_factory=lambda: [15.0] * 256)
    pressure: List[float] = field(default_factory=lambda: [1013.25] * 256)
    humidity: List[float] = field(default_factory=lambda: [0.5] * 256)
    wind_u: List[float] = field(default_factory=lambda: [0.0] * 256)
    wind_v: List[float] = field(default_factory=lambda: [0.0] * 256)
    cloud_cover: List[float] = field(default_factory=lambda: [0.0] * 256)
    precipitation: List[float] = field(default_factory=lambda: [0.0] * 256)
    
    climate: ClimateType = ClimateType.TEMPERATE
    dirty_climate: bool = True


@dataclass
class StormInfluence:
    """Transient influence buffer generated by StormSystem and consumed downstream."""
    chunk_id: int
    vorticity_boost: float = 0.0
    moisture_uplift: float = 0.0
    pressure_drop: float = 0.0


@dataclass
class ThermalConfig:
    lapse_rate: float = 0.0065  # °C per meter
    specific_heat_air: float = 1005.0


# =====================================================================
# 2. ROLLING STATISTICS & DEFERRED UPDATES
# =====================================================================

class RollingAtmosphericStats:
    """Maintains world-level statistics incrementally to eliminate O(N) full-world scans."""
    
    def __init__(self) -> None:
        self.total_chunks: int = 0
        self.sum_temperature: float = 0.0
        self.sum_pressure: float = 0.0
        
    def register_chunk(self, chunk: ChunkData) -> None:
        self.total_chunks += 1
        self.sum_temperature += sum(chunk.temperature) / len(chunk.temperature)
        self.sum_pressure += sum(chunk.pressure) / len(chunk.pressure)

    def update_chunk_deltas(
        self,
        chunk_id: int,
        temp_delta: float,
        pressure_delta: float,
        cell_count: int = 256
    ) -> None:
        self.sum_temperature += temp_delta / cell_count
        self.sum_pressure += pressure_delta / cell_count

    @property
    def mean_temperature(self) -> float:
        return self.sum_temperature / max(1, self.total_chunks)

    @property
    def mean_pressure(self) -> float:
        return self.sum_pressure / max(1, self.total_chunks)


