class WeatherPipeline:
    """Manages stage registration, dependency validation, and stage execution."""
    
    def __init__(self) -> None:
        self._stages: List[ISolverStage] = []

    def register_stage(self, stage: ISolverStage) -> None:
        self._stages.append(stage)
        self._validate_pipeline()

    def _validate_pipeline(self) -> None:
        executed: set = set()
        for stage in self._stages:
            for dep in stage.dependencies:
                if dep not in executed:
                    raise RuntimeError(
                        f"Pipeline Dependency Error: Stage '{stage.name}' requires '{dep}' "
                        f"which has not executed yet."
                    )
            executed.add(stage.name)

    def execute(
        self,
        chunks: List[ChunkData],
        season: SeasonState,
        dt: float
    ) -> Dict[int, StormInfluence]:
        storm_influences: Dict[int, StormInfluence] = {}
        for stage in self._stages:
            stage.execute(chunks, season, storm_influences, dt)
        return storm_influences


class AtmosphericGrid:
    """Grid storage container with bilinear spatial sampling."""
    
    def __init__(self, chunks: List[ChunkData]) -> None:
        self.chunks: List[ChunkData] = chunks

    def sample_temperature_bilinear(self, x: float, y: float, chunk_id: int) -> float:
        """Bilinear interpolation across grid cells."""
        chunk = self.chunks[chunk_id]
        grid_size = 16
        
        gx = max(0.0, min(grid_size - 1.001, x))
        gy = max(0.0, min(grid_size - 1.001, y))
        
        x0, y0 = int(gx), int(gy)
        x1, y1 = min(x0 + 1, grid_size - 1), min(y0 + 1, grid_size - 1)
        
        dx, dy = gx - x0, gy - y0
        
        t00 = chunk.temperature[y0 * grid_size + x0]
        t10 = chunk.temperature[y0 * grid_size + x1]
        t01 = chunk.temperature[y1 * grid_size + x0]
        t11 = chunk.temperature[y1 * grid_size + x1]
        
        top = t00 * (1 - dx) + t10 * dx
        bottom = t01 * (1 - dx) + t11 * dx
        return top * (1 - dy) + bottom * dy


class WeatherManager:
    """Engine orchestrator coordinating pipeline, deferrals, and statistics."""
    
    def __init__(self, grid: AtmosphericGrid) -> None:
        self.grid = grid
        self.season_state = SeasonState()
        self.pipeline = WeatherPipeline()
        self.stats = RollingAtmosphericStats()
        self.climate_classifier = ClimateClassifier(interval_ticks=100)
        
        # Initialize stats cache
        for chunk in self.grid.chunks:
            self.stats.register_chunk(chunk)
            
        self._setup_default_pipeline()

    def _setup_default_pipeline(self) -> None:
        thermal_config = ThermalConfig(lapse_rate=0.0065)
        self.pipeline.register_stage(ThermalSolver(thermal_config))
        self.pipeline.register_stage(PressureFieldSolver())
        self.pipeline.register_stage(MoistureSolver())
        self.pipeline.register_stage(StormSystem())
        self.pipeline.register_stage(CloudFormationSolver())

    def update(self, dt: float) -> None:
        # Advance season state
        self.season_state.day_of_year = (self.season_state.day_of_year + dt) % 365.0
        self.season_state.insolation_factor = 0.5 + 0.5 * math.sin(
            (self.season_state.day_of_year / 365.0) * 2.0 * math.pi
        )
        
        # Execute decoupled deterministic pipeline
        self.pipeline.execute(self.grid.chunks, self.season_state, dt)
        
        # Interval/Deferred classification step
        self.climate_classifier.tick(self.grid.chunks)


